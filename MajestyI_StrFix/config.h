#pragma once

// MajestyI_StrFix.dll —— ASI 插件配置
// 说明：本文件是「唯一配置源」。修改后重启游戏生效。

// 日志级别：0=关闭 1=仅摘要/命中 2=命中+详情(默认) 3=全量(含未命中/每次赋值)
// ★ 诊断已完成，回落到 2（3 会 dump 每次赋值，日志高达 1.5MB）。
#define LOG_LEVEL   2

// 是否把「未命中(纯 ASCII)」也记进日志的计数里（不写逐条明细，只累计数字）
#define LOG_COUNT_MISS      1

// 是否 hook sub_627AD0(宽串赋值) 做只读观测（不改变行为）
#define HOOK_WIDE_ASSIGN_OBSERVE   0

// 是否在转发原函数前，把待转换的 ANSI 源串打 dump（含十六进制）
#define LOG_DUMP_SOURCE     1

// 单条日志最多 dump 多少字节源串
#define LOG_DUMP_MAX_BYTES  64

// ---------------------------------------------------------------------------
// ★★★ 根治开关（v1.2）
// ---------------------------------------------------------------------------

// hook sub_627890（全引擎唯一的 StrObj 缓冲分配入口），分配后立即清零缓冲。
// 这是死循环的根治点：任何「只分配、不填充内容」的路径都会变成空串
// （首字符即 '\0'），宽扫描立即终止，物理上不可能死循环。
#define STRFIX_ZERO_ON_ALLOC    1

// 清洗 flags 高字节里的「已知堆填充值」（0xBA/0xAB/0xFE/0xCD/0xDD/0xFD/0xCC）。
// 这些是 MSVC 调试堆填充（BAADF00D/ABABABAB/FEEEFEEE/…）的首字节，
// 一旦 bit0 碰巧为 1，引擎就会把 ANSI/垃圾缓冲按 UTF-16 解读。
// 只清「已知填充」，保留 0x10/0x02 等可能合法的标志位。
#define STRFIX_SANITIZE_FLAGS   1

// 清零时单块缓冲的字符数上限，超过则跳过（防止异常 count 导致 memset 崩溃）
#define STRFIX_ZERO_MAX_CHARS   (1024 * 1024)

// ---------------------------------------------------------------------------
// ★★★ v1.4：CAM 的 UTF-16LE 路径识别（非 XML/MQXML 驱动）
// ---------------------------------------------------------------------------
// 实证（mx_btdata.cam / mx_textdata.cam / textdata.cam）：
//   CAM 里字符串记录的字节布局是
//        [key][FF FE][UTF-16LE 正文][00 00]
//   而 CAM 加载器把「正文起点」（即 BOM+2）当 const char* 传给 sub_627AD0，
//   且 count = 字节数(=2×字符数) → 得到「ANSI 容器装 UTF-16 字节」的 StrObj：
//        data = D8 9E A4 8B 00  (UTF-16LE "默认")   flags = 0x00 (ANSI!)  len = 4
//   排版测宽时按单字节读 0xD8/0x9E… 宽度表查不到 → 溢出 → 位置不前进 → 死循环。
//
// 识别特征（两个都不依赖内容猜测，只认 BOM）：
//   (a) src 前 2 字节 == FF FE  ← CAM 记录形态（主路径）
//   (b) src 自身 == FF FE      ← 调用方把含 BOM 的整串传进来
// 命中后直接把该 UTF-16LE 正文原地转存为引擎的 wide StrObj，
// 引擎后续全链路自动走 wide 分支，与 XML/MQXML 修复路径一致。
#define STRFIX_DETECT_UTF16   1

// ---------------------------------------------------------------------------
// ★★★ v1.5：UTF-16LE 源串的「内容形态嗅探」（BOM 之外的兜底）
// ---------------------------------------------------------------------------
// 实证（2026-09-10 x32dbg，游戏卡在「自定义玩法手动设置」UI）：
//   坏 StrObj： data=0x0D3A3180  [+4]=0x00000004 (len=4, flags=0x00 ANSI)  [+8]=4
//              data 内容 = D8 9E A4 8B 00  (UTF-16LE "默认") + 堆填充
//              data 只被写了 5 字节（memcpy(4)+NUL）→ 正是 sub_627AD0 窄分支
//              malloc(count+1) 的形态。
//
//   矛盾点：这条源串【没有 BOM 前缀】，所以 STRFIX_DETECT_UTF16 漏掉了它。
//   而且 IsValidUtf8WithMultibyte("D8 9E A4 8B") 返回 false
//   （0xA4 = 1010_0100，既不是合法 UTF-8 首字节也不是续字节）→ 被当纯 ASCII
//   原样转发 → 窄分支 → ANSI 容器装 UTF-16 字节 → 测宽溢出 → 死循环。
//
//   兜底判据（不依赖 BOM，只看内容形态）：
//     · 字节数为偶数，且 >= 4（至少 2 个 wide 单元）
//     · 至少有一个字节 >= 0x80（排除纯 ASCII，纯 ASCII 不会死循环）
//     · 按 UTF-16LE 解出的每个单元都必须是「合理可显示宽字符」
//     · 其中至少 1/3 的单元落在 CJK/假名/谚文/全角区（排除拉丁 ANSI 误判）
//   命中后与 BOM 路径走同一段 TryStoreUtf16Wide，零额外风险。
#define STRFIX_SNIFF_UTF16    1

// ---------------------------------------------------------------------------
// ★★★ v1.6：消费者侧自愈（不依赖找到生产者）
// ---------------------------------------------------------------------------
// 背景（2026-09-10 23:0x，x32dbg 线程级采样）：
//   v1.5 部署后 sniff 计数仍为 0，而「自定义玩法手动设置」依旧死循环。
//   线程级 EIP 采样定位到真正自旋线程（Thread 56564，非主线程）：
//       5 × 0x0066CBEB (sub_66CA70 测宽累加)
//       2 × 0x0066CD51 / 1 × 0x0066CDFE + 0x0066CE29 (sub_66CDA0)
//   即死循环确在「测宽/测行」簇内，但对象并非由 sub_627A80/627AD0 生产
//   （存在第 3 条未 hook 的赋值路径，追不到）。
//
// 方案：不再追生产者，改为在【所有测量必经的消费者入口】做一次性形态自愈：
//   · narrow(flags=0) 但内容按 UTF-16LE 解读合理 → 原地转成 wide StrObj
//   · wide(flags&1) 但限长内找不到 0x0000 终止符 → 强制置空串（len=0）
//   自愈后 flags 与内容一致，测宽循环必然前进，物理上不可能再死循环。
//   ★ 自愈是幂等的：修好后 flags 已正确，下次快速路径直接跳过，不会反复分配。
#define STRFIX_HEAL_CONSUMER   1

// 自愈时记录调用方返回地址的条数上限（用于反查生产者路径，之后改为每 1000 条一次）
#define STRFIX_HEAL_LOG_DETAIL 20

// wide 串「找终止符」的扫描上限（wchar 个数）。超过则视为异常长度。
#define STRFIX_HEAL_SCAN_WORDS 8192

// narrow 串既不是 UTF-16LE 也不是 UTF-8，但字节全落在 Latin-1 可打印区
// (0x80 以下的 ASCII 或 0xA0..0xFF) → 按 byte→wchar 1:1 映射转 wide。
// 保留西文重音字符，且宽表必有这些字形，必然终止。
#define STRFIX_HEAL_LATIN1     1

// 最后兜底：narrow 串含高位字节、两种解码都不成立、且含 C1 控制符
// (0x80..0x9F —— 宽表一定没有字形，会再次死循环) → 强制空串。
// 宁可少显示一段文本，也不让游戏无响应。
#define STRFIX_HEAL_EMPTY_JUNK 1

// 日志文件名（相对游戏根目录/ASI 所在目录）
#define LOG_FILE_NAME   "MajestyI_StrFix.log"
